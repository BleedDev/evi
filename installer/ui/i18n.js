const LANGS = Object.keys(STRINGS);

/** The best language for a tag like `de-AT` or `pt_BR`: the exact tag, else the same language */
function pickLanguage(tags) {
    for (const tag of tags) {
        const want = String(tag).replace(/_/g, "-").toLowerCase();
        const exact = LANGS.find(l => l.toLowerCase() === want);
        if (exact) return exact;
        const base = want.split("-")[0];
        const same = LANGS.find(l => l.toLowerCase().split("-")[0] === base);
        if (same) return same;
    }
    return "en";
}

const LANG = pickLanguage(navigator.languages && navigator.languages.length ? navigator.languages : [navigator.language || "en"]);

function t(key, vars) {
    const text = STRINGS[LANG][key] ?? STRINGS.en[key] ?? key;
    return vars ? text.replace(/\{(\w+)\}/g, (whole, name) => name in vars ? String(vars[name]) : whole) : text;
}

/** "Stable and PTB" in the language's own way of joining */
function joinList(items) {
    try {
        return new Intl.ListFormat(LANG, { style: "long", type: "conjunction" }).format(items);
    } catch {
        return items.join(", ");
    }
}

/** Fills the static text of index.html: data-i18n for text, data-i18n-label for aria-labels */
function translatePage() {
    document.documentElement.lang = LANG;
    for (const el of document.querySelectorAll("[data-i18n]")) el.textContent = t(el.dataset.i18n);
    for (const el of document.querySelectorAll("[data-i18n-label]")) el.setAttribute("aria-label", t(el.dataset.i18nLabel));
}
