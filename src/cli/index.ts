/**
 * evi install    [--flavor stable|ptb|canary|development|all] [--dev] [--restart | --wait]
 * evi uninstall  [--flavor ...] [--restart]
 * evi status
 * evi update     [--check] [--beta] [--flavor ...] [--restart]
 */
import { existsSync, mkdirSync, readFileSync, renameSync, rmSync, writeFileSync } from "fs";
import { join, resolve } from "path";
import { parseArgs } from "util";

import pkg from "../../package.json";
import { FLAVORS } from "../shared/release";
import { ORIGINAL_ASAR } from "../shared/shim";
import { parseRemovedPlugins, REMOVED_PLUGINS_FILE, RETIRED_PLUGINS, STORE_MARKER } from "../shared/store";
import { DiscordInstall, findInstalls, injectionState, isDiscordRunning, killDiscord, searchedLocations, startDiscord, waitForExit } from "./discord";
import { APP_DATA, giveBackToUser, isSudo } from "./paths";
import { swapIn, swapOut } from "./swap";
import { cleanupPreviousUpdate, COMPILED, downloadVerified, fetchLatestRelease, isNewer, missingExe, replaceExecutable, UpdateError } from "./update";

interface Embed {
    version: string;
    core: Record<string, string>;
    plugins: Record<string, Record<string, string>>;
}

const DATA_DIR = join(APP_DATA, "Evi");

// Before the rename to Evi the data folder was %APPDATA%/Delight: move it over once
const LEGACY_DATA_DIR = join(APP_DATA, "Delight");
if (APP_DATA && !existsSync(DATA_DIR) && existsSync(LEGACY_DATA_DIR)) {
    try {
        renameSync(LEGACY_DATA_DIR, DATA_DIR);
    } catch { }
}

const { values: flags, positionals } = parseArgs({
    args: Bun.argv.slice(2),
    allowPositionals: true,
    options: {
        flavor: { type: "string", default: "stable" },
        dev: { type: "boolean", default: false },
        restart: { type: "boolean", default: false },
        wait: { type: "boolean", default: false },
        check: { type: "boolean", default: false },
        beta: { type: "boolean", default: false },
        help: { type: "boolean", short: "h", default: false },
    },
});

const c = {
    ok: (s: string) => `\x1b[32m${s}\x1b[0m`,
    warn: (s: string) => `\x1b[33m${s}\x1b[0m`,
    err: (s: string) => `\x1b[31m${s}\x1b[0m`,
    dim: (s: string) => `\x1b[2m${s}\x1b[0m`,
    bold: (s: string) => `\x1b[1m${s}\x1b[0m`,
};

function fail(message: string): never {
    console.error(c.err(`✗ ${message}`));
    process.exit(1);
}

function selectedInstalls() {
    const installs = findInstalls();
    if (!installs.length) fail(`No Discord installation found in ${searchedLocations()}.`);
    if (flags.flavor === "all") return installs;
    if (!(flags.flavor! in FLAVORS)) fail(`Unknown flavor "${flags.flavor}". Use one of: ${Object.keys(FLAVORS).join(", ")}, all`);

    const install = installs.find(i => i.flavor === flags.flavor);
    if (!install) fail(`Discord ${flags.flavor} isn't installed. Found: ${installs.map(i => i.flavor).join(", ")}`);
    return [install];
}

async function loadEmbed(): Promise<Embed> {
    try {
        // @ts-ignore Generated by scripts/build.ts, and bundled into the compiled exe
        return (await import("../../dist/embed.json")).default;
    } catch {
        fail("No build found. Run `bun run build` first, or use --dev.");
    }
}

/** Where the shim should point: the repo build in dev mode, otherwise a copy in the data folder */
async function prepareCore(): Promise<{ corePath: string; devPluginsDir?: string; }> {
    if (flags.dev) {
        const root = resolve(import.meta.dir, "..", "..");
        const corePath = join(root, "dist", "core", "main.js");
        if (!existsSync(corePath)) fail("dist/core/main.js is missing. Run `bun run build` (or `bun run dev`) first.");
        return { corePath, devPluginsDir: join(root, "dist", "plugins") };
    }

    const embed = await loadEmbed();
    const coreDir = join(DATA_DIR, "core");
    rmSync(coreDir, { recursive: true, force: true });
    mkdirSync(coreDir, { recursive: true });
    for (const [file, content] of Object.entries(embed.core)) writeFileSync(join(coreDir, file), content);
    writeFileSync(join(coreDir, "package.json"), JSON.stringify({ type: "commonjs" }));

    // Evi comes with no plugins: they're added from the store. Official plugins someone already has
    // (from before, when every install laid them all down) are kept up to date; ones they removed or
    // installed from the store are left alone, and nothing new is added.
    const removed = existsSync(join(DATA_DIR, REMOVED_PLUGINS_FILE)) ? parseRemovedPlugins(readFileSync(join(DATA_DIR, REMOVED_PLUGINS_FILE), "utf8")) : new Set<string>();
    for (const [id, files] of Object.entries(embed.plugins)) {
        const dir = join(DATA_DIR, "plugins", id);
        if (removed.has(id) || !existsSync(join(dir, "manifest.json")) || existsSync(join(dir, STORE_MARKER))) continue;
        rmSync(dir, { recursive: true, force: true });
        mkdirSync(dir, { recursive: true });
        for (const [file, content] of Object.entries(files)) writeFileSync(join(dir, file), content);
    }

    // Official plugins that are now part of Evi itself would show up twice
    for (const id of RETIRED_PLUGINS) {
        const dir = join(DATA_DIR, "plugins", id);
        if (!existsSync(join(dir, STORE_MARKER))) rmSync(dir, { recursive: true, force: true });
    }
    giveBackToUser(DATA_DIR);

    return { corePath: join(coreDir, "main.js") };
}

/** Why the archives couldn't be swapped, with what to do about it */
function permissionHint(install: DiscordInstall, err: unknown) {
    const code = (err as NodeJS.ErrnoException)?.code;
    if (code !== "EACCES" && code !== "EPERM") return;
    if (process.platform === "darwin") {
        return `macOS didn't let this terminal change ${install.root}. Allow it in System Settings > Privacy & Security > App Management, then try again.`;
    }
    if (process.platform === "linux" && !isSudo()) {
        return `${install.root} belongs to root. Run it again with sudo: sudo ${COMPILED ? process.execPath : "bun src/cli/index.ts"} ${Bun.argv.slice(2).join(" ")}`;
    }
}

/**
 * Discord keeps app.asar open while running, so it has to be closed to swap the archives.
 * Returns false when it's running and we weren't allowed to close it, or the swap failed.
 */
async function withDiscordClosed(install: DiscordInstall, action: () => void) {
    const running = isDiscordRunning(install);
    if (running && !flags.restart) {
        console.error(c.err(`✗ Discord ${install.flavor} is running. Quit it fully (tray icon > Quit), or pass --restart.`));
        return false;
    }
    if (running) await killDiscord(install);
    try {
        action();
    } catch (err) {
        const hint = permissionHint(install, err);
        if (!hint) throw err;
        console.error(c.err(`✗ ${hint}`));
        return false;
    } finally {
        if (running && !startDiscord(install)) console.log(c.dim(`  Start Discord ${install.flavor} again yourself: under sudo it would run as root.`));
    }
    return true;
}

async function install() {
    const installs = selectedInstalls();
    // Started by the in-app updater as Discord quits: give it time to exit, and never close it. Checked
    // before anything is written, so a Discord that stays open (or was opened again) keeps its version
    if (flags.wait && !flags.restart) {
        for (const discord of installs) {
            if (!(await waitForExit(discord))) fail(`Discord ${discord.flavor} is still running, so nothing was changed. Quit it fully and run this again.`);
        }
    }
    // The core is shared by every Discord: only rewrite it when at least one can take Evi
    const targets = installs.flatMap(discord => {
        const { resources, version } = discord.versions[0];
        const state = injectionState(resources);
        if (state !== "other-mod") return [{ discord, resources, version, state }];
        console.error(c.err(`✗ ${discord.flavor} ${version}: another client mod (Vencord, Equicord, ...) is installed. Uninstall it first.`));
        return [];
    });
    if (!targets.length) return;
    const core = await prepareCore();

    for (const { discord, resources, version, state } of targets) {
        const done = await withDiscordClosed(discord, () => swapIn(resources, state, core));
        if (!done) continue;

        console.log(c.ok(`✓ ${state === "evi" ? "Updated" : "Installed"} Evi in Discord ${discord.flavor} ${version}`) + c.dim(flags.dev ? " (dev build)" : ""));
    }
}

async function uninstall() {
    for (const discord of selectedInstalls()) {
        // Nothing to remove: never close a Discord (and drop its call) for that
        if (!discord.versions.some(v => injectionState(v.resources) === "evi")) {
            console.log(c.dim(`  Evi wasn't installed in Discord ${discord.flavor}`));
            continue;
        }
        let removed = 0;
        let missing = 0;
        const done = await withDiscordClosed(discord, () => {
            // Every version folder, the auto-repair may have injected older ones too
            for (const { resources } of discord.versions) {
                if (injectionState(resources) !== "evi") continue;
                if (swapOut(resources)) removed++;
                else {
                    missing++;
                    console.error(c.err(`✗ Discord's own archive (${ORIGINAL_ASAR}) is missing from ${resources}, so Evi was left there.`));
                }
            }
        });
        if (!done || (missing && !removed)) continue;
        console.log(removed ? c.ok(`✓ Removed Evi from Discord ${discord.flavor}`) : c.dim(`  Evi wasn't installed in Discord ${discord.flavor}`));
    }
}

function status() {
    const installs = findInstalls();
    if (!installs.length) return console.log("No Discord installation found.");

    for (const discord of installs) {
        const { version, resources } = discord.versions[0];
        const state = injectionState(resources);
        const label = { clean: c.dim("not installed"), evi: c.ok("installed"), "other-mod": c.warn("another mod is installed") }[state];
        const running = isDiscordRunning(discord) ? c.dim(" · running") : "";
        console.log(`${c.bold(discord.flavor.padEnd(12))} ${version.padEnd(10)} ${label}${running}`);
    }
    console.log(c.dim(`\nData folder: ${DATA_DIR}`));
}

/** Replaces this exe with the latest published release, then lets the new exe run `install` */
async function update() {
    const current = pkg.version;
    const sourceHint = "This is a source checkout. Update it with `git pull` and `bun run build`.";

    let release;
    try {
        release = await fetchLatestRelease(flags.beta);
    } catch (e) {
        fail(e instanceof UpdateError ? e.message : String(e));
    }

    if (!release) {
        console.log(`No Evi release has been published yet. You have ${current}.`);
        if (!COMPILED) console.log(c.dim(sourceHint));
        return;
    }
    if (!isNewer(release.tag, current)) {
        console.log(c.ok(`✓ Evi ${current} is up to date`) + c.dim(` (latest release: ${release.tag})`));
        return;
    }

    console.log(`Evi ${release.version} is available, you have ${current}.`);
    if (!COMPILED) return console.log(c.dim(sourceHint));
    const missing = missingExe(release);
    if (missing && flags.check) return console.log(c.dim(missing));
    if (missing) fail(missing);
    if (flags.check) return console.log(c.dim(`Run \`evi update\` to install it. ${release.url}`));

    const exe = process.execPath;
    try {
        console.log(c.dim(`Downloading ${release.tag}…`));
        const bytes = await downloadVerified(release);
        replaceExecutable(exe, bytes);
    } catch (e) {
        fail(e instanceof UpdateError ? e.message : String(e));
    }
    console.log(c.ok(`✓ Updated ${exe} to ${release.version}`));

    // Refresh only Discords that already have Evi: updating must never inject into one you didn't choose.
    // The new exe carries the new core and official plugins, so it does the install.
    const installed = findInstalls().filter(d => injectionState(d.versions[0].resources) === "evi");
    if (!installed.length) {
        console.log(c.dim("Evi isn't installed in any Discord yet. Run `evi install` to add it."));
        return;
    }
    for (const discord of installed) {
        const args = [exe, "install", "--flavor", discord.flavor, ...(flags.restart ? ["--restart"] : [])];
        const code = await Bun.spawn(args, { stdio: ["inherit", "inherit", "inherit"] }).exited;
        if (code !== 0) fail(`The new version is in place, but refreshing Discord ${discord.flavor} failed. Run \`evi install --flavor ${discord.flavor}\` to retry.`);
    }
}

function help() {
    console.log(`${c.bold("evi")} ${pkg.version} — Discord client mod installer

  install     Install or update Evi
  uninstall   Remove Evi, Discord goes back to vanilla
  status      Show every Discord install and whether Evi is in it
  update      Download the latest release and refresh every Discord that has Evi

Options
  --flavor <stable|ptb|canary|development|all>   Which Discord (default: stable)
  --restart                                      Quit and reopen Discord for you
  --wait                                         With install: wait up to a minute for Discord to quit, never close it
  --dev                                          Point Discord at this repo's dist/ (hot reload)
  --check                                        With update: only report whether a newer release exists
  --beta                                         With update: include beta versions (prereleases)

Launch Discord with --vanilla to start it once without Evi.${process.platform === "linux" ? "\nDiscord's folder usually belongs to root on Linux: run install, uninstall and update with sudo." : ""}`);
}

if (COMPILED) cleanupPreviousUpdate(process.execPath);

const commands: Record<string, () => unknown> = { install, repair: install, uninstall, status, update, help };
const command = flags.help ? "help" : positionals[0] ?? "help";
if (!(command in commands)) fail(`Unknown command "${command}". Run \`evi help\`.`);
await commands[command]();
